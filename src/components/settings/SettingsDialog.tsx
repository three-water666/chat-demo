const SettingsContent = () => {
  const t = useTranslate()
  const section = useSettingsDialog((state) => state.section)
  // 切换分组不丢失正在输入的 API Key 与导入状态
  const apiKeyEditor = useApiKeyEditor()
  const historyImport = useHistoryImport()
  const historyDelete = useHistoryDelete()
  const clearingHistory = useChatStore((state) => state.importingHistory)
  const historyBusy = historyImport.step !== null || historyDelete.busy || clearingHistory
  return (
    <>
      <Modal
        title={t('settings')}
        closable
        className={styles.dialog}
        mainClassName={styles.dialogMain}
        onClose={() => {
          if (!historyDelete.busy && !historyImport.saving) {
            closeSettings()
          }
        }}
      >
        <div role="tablist" className={styles.navigation}>
          {sections.map((item) => (
            <button
              key={item.value}
              type="button"
              role="tab"
              aria-selected={section === item.value}
              className={clsx(styles.navItem, section === item.value && styles.navItemActive)}
              onClick={() => openSettings(item.value)}
            >
              {item.icon}
              {t(item.label)}
            </button>
          ))}
        </div>
        <div key={section} role="tabpanel" className={styles.content}>
          {section === 'api' ? (
            <>
              <ApiKeyField editor={apiKeyEditor} />
              <BalanceSetting />
            </>
          ) : section === 'general' ? (
            <>
              <ThemeSetting />
              <LocaleSetting />
              <TtsVoiceSetting />
              <LocationSetting />
            </>
          ) : (
            <>
              <SettingCell
                className={styles.historyImportCell}
                label={t('historyImport')}
                description={t('historyImportDescription')}
                status={historyImport.status}
                action={<HistoryImportActions control={historyImport} disabled={historyBusy} />}
              />
              <ExportHistory disabled={historyBusy} />
              <SettingCell
                label={t('deleteAllSessions')}
                status={null}
                action={
                  <Button
                    variant="dangerOutlined"
                    size="m"
                    className={styles.cellButton}
                    disabled={historyBusy}
                    onClick={historyDelete.open}
                  >
                    {t('delete')}
                  </Button>
                }
              />
            </>
          )}
        </div>
      </Modal>
      <HistoryImportDialog control={historyImport} />
      {historyDelete.opened ? <DeleteAllConfirm historyDelete={historyDelete} /> : null}
    </>
  )
}

/** 删除确认保留在设置之上；失败可重试，成功只关闭确认弹窗。 */
const DeleteAllConfirm = ({
  historyDelete,
}: {
  historyDelete: ReturnType<typeof useHistoryDelete>
}) => {
  const t = useTranslate()
  return (
    <Modal
      title={t('deleteAllSessionsModalTitle')}
      className={styles.deleteConfirm}
      onClose={historyDelete.cancel}
      footer={
        <div className={styles.deleteActions} aria-busy={historyDelete.busy}>
          <Button
            variant="outlined"
            autoFocus
            disabled={historyDelete.busy}
            onClick={historyDelete.cancel}
          >
            {t('cancel')}
          </Button>
          <Button
            variant="danger"
            disabled={historyDelete.busy}
            onClick={() => void historyDelete.confirm()}
          >
            {t(historyDelete.busy ? 'historyDeleting' : 'deleteAllSessions')}
          </Button>
        </div>
      }
    >
      {t('deleteAllSessionsModalDescription')}
    </Modal>
  )
}

const useHistoryDelete = () => {
  const [opened, setOpened] = useState(false)
  const [busy, setBusy] = useState(false)
  const deleting = useRef(false)

  const confirm = async () => {
    if (deleting.current) {
      return
    }
    deleting.current = true
    setBusy(true)
    try {
      await clearHistory()
      setOpened(false)
      showToast({ key: 'historyDeleted' })
    } catch {
      showToast({ key: 'historyDeleteFailed', type: 'error' })
    } finally {
      deleting.current = false
      setBusy(false)
    }
  }

  return {
    opened,
    busy,
    open: () => setOpened(true),
    cancel: () => {
      if (!deleting.current) {
        setOpened(false)
      }
    },
    confirm,
  }
}

const BalanceSetting = () => {
  const t = useTranslate()
  const apiKey = useSettings((state) => state.apiKey)
  const { balances, error, loading, refreshBlocked } = useAccountBalance()
  const { onTopUp, refresh } = useBalanceRefresh(apiKey, loading || refreshBlocked)
  const linkClassName = clsx(
    buttonStyles.button,
    buttonStyles.m,
    styles.cellButton,
    styles.balanceLink
  )

  const amount = balances
    ?.map(({ currency, total_balance }) => `${currency === 'CNY' ? '¥' : 'US$'}${total_balance}`)
    .join(' · ')
  const errorKey =
    error === 'unauthorized'
      ? 'replyInvalidApiKey'
      : error === 'rateLimited'
        ? 'replyRateLimited'
        : 'balanceLoadFailed'

  return (
    <SettingCell
      label={t('settingsBalance')}
      className={styles.balanceCell}
      status={null}
      description={
        <div role="status">
          {!apiKey ? t('balanceNeedsApiKey') : null}
          {loading && !amount ? t('balanceLoading') : null}
          {amount ? <div className={styles.balanceAmount}>{amount}</div> : null}
          {balances?.length === 0 && !loading && !error ? t('balanceEmpty') : null}
          {error ? <div className={styles.error}>{t(errorKey)}</div> : null}
        </div>
      }
      action={
        <div className={styles.balanceActions}>
          <Button
            variant="outlined"
            size="m"
            className={styles.cellButton}
            disabled={!apiKey || loading || refreshBlocked}
            aria-busy={loading}
            onClick={refresh}
          >
            <IconRefreshOutline16 />
            {t('balanceRefresh')}
          </Button>
          <PlatformLink
            className={clsx(linkClassName, buttonStyles.outlined)}
            href="https://platform.deepseek.com/usage"
          >
            {t('viewApiUsage')}
          </PlatformLink>
          <PlatformLink
            className={clsx(linkClassName, buttonStyles.primary)}
            href={TOP_UP_URL}
            onOpen={onTopUp}
          >
            {t('topUp')}
          </PlatformLink>
        </div>
      }
    />
  )
}

const LocationSetting = () => {
  const t = useTranslate()
  const locale = useSettings((state) => state.locale)
  const location = useSettings((state) => state.location)
  const province =
    location?.region === 'CN'
      ? provinces.find((item) => item.code === location.province)
      : undefined

  return (
    <SettingCell
      label={t('settingsLocation')}
      status={null}
      className={styles.locationCell}
      action={
        <div className={styles.locationSelectors}>
          {isChineseBrowser() ? (
            <>
              <Select
                ariaLabel={t('settingsLocationProvince')}
                className={styles.provinceSelect}
                value={province?.code ?? ''}
                placeholder={t('settingsLocationProvince')}
                options={provinces.map((item) => ({ value: item.code, label: item.name }))}
                onChange={(value) => {
                  if (value !== province?.code) {
                    setLocation({ region: 'CN', province: value })
                  }
                }}
              />
              <Select
                ariaLabel={t('settingsLocationCity')}
                className={styles.citySelect}
                value={province ? (location?.city ?? '') : ''}
                disabled={!province?.cities.length}
                placeholder={t('settingsLocationCity')}
                options={
                  province?.cities.map((item) => ({ value: item.code, label: item.name })) ?? []
                }
                onChange={(value) => {
                  if (province) {
                    setLocation({ region: 'CN', province: province.code, city: value })
                  }
                }}
              />
            </>
          ) : (
            <Select
              ariaLabel={t('settingsLocationRegion')}
              className={styles.regionSelect}
              value={location?.region ?? ''}
              placeholder={t('settingsLocationRegion')}
              options={regionCodes
                .map((code) => ({ value: code, label: getRegionName(code, locale) }))
                .sort((a, b) => a.label.localeCompare(b.label, locale))}
              onChange={(value) => setLocation({ region: value })}
            />
          )}
        </div>
      }
    />
  )
}

